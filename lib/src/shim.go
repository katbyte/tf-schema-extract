package src

// shimDirName is created inside the provider module root so the shim compiles with the
// provider's own go.mod (and vendor directory) and can import its internal packages.
const shimDirName = "tfschemaex-shim"

// shimTemplate is the generated program that walks the live *schema.Provider.
//
// It must compile against any terraform-plugin-sdk v2 version a provider might pin, so
// fields added to the SDK over time (WriteOnly, DiffSuppressOnRefresh, SchemaFunc, ...)
// are read via reflection instead of direct field access. It deliberately avoids struct
// tags (and therefore backticks) so it can live in this raw string. Output is written to
// the file given as os.Args[1] since providers can print noise to stdout during init.
const shimTemplate = `package main

// generated by tfschemaex - walks the provider schema in-process and dumps it as JSON.
// safe to delete.

import (
	__IMPORT_CONTEXT__
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"reflect"
	"regexp"
	"runtime"
	"strings"

	"github.com/hashicorp/terraform-plugin-sdk/v2/helper/schema"

	entry "__ENTRY_PACKAGE__"
)

var cwd string

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: shim <output.json>")
		os.Exit(1)
	}
	cwd, _ = os.Getwd()

	__ENTRY_CALL__

	out := map[string]any{
		"provider": map[string]any{
			"schema":    schemaMapJSON(p.Schema),
			"configure": firstRef(p.ConfigureContextFunc, p.ConfigureFunc),
		},
		"resources":    resourceMapJSON(p.ResourcesMap),
		"data_sources": resourceMapJSON(p.DataSourcesMap),
	}

	if fw := frameworkJSON(p); fw != nil {
		out["framework"] = fw
	}

	data, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		fmt.Fprintf(os.Stderr, "shim: marshalling schema: %v\n", err)
		os.Exit(1)
	}
	if err := os.WriteFile(os.Args[1], data, 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "shim: writing output: %v\n", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "shim: dumped %d resources, %d data sources\n", len(p.ResourcesMap), len(p.DataSourcesMap))
}

func resourceMapJSON(in map[string]*schema.Resource) map[string]any {
	out := make(map[string]any, len(in))
	for name, r := range in {
		out[name] = resourceJSON(r, false)
	}
	return out
}

func resourceJSON(r *schema.Resource, isElem bool) map[string]any {
	if r == nil {
		return nil
	}

	s := r.Schema
	if s == nil {
		// SchemaFunc (sdk v2.31+) lazily builds the schema; call it via reflection so
		// this still compiles against older SDKs that lack the field
		if fn, ok := fieldValue(r, "SchemaFunc"); ok && fn.Kind() == reflect.Func && !fn.IsNil() {
			if res := fn.Call(nil); len(res) == 1 {
				if m, ok := res[0].Interface().(map[string]*schema.Schema); ok {
					s = m
				}
			}
		}
	}

	out := map[string]any{
		"schema": schemaMapJSON(s),
	}

	// an Elem resource only carries a schema; everything below is top-level-resource only
	if isElem {
		return out
	}

	out["schema_version"] = r.SchemaVersion
	addString(out, "description", stringField(r, "Description"))
	addString(out, "deprecation_message", r.DeprecationMessage)

	addRef(out, "create", firstRef(anyField(r, "CreateWithoutTimeout"), r.CreateContext, r.Create))
	addRef(out, "read", firstRef(anyField(r, "ReadWithoutTimeout"), r.ReadContext, r.Read))
	addRef(out, "update", firstRef(anyField(r, "UpdateWithoutTimeout"), r.UpdateContext, r.Update))
	addRef(out, "delete", firstRef(anyField(r, "DeleteWithoutTimeout"), r.DeleteContext, r.Delete))
	addRef(out, "exists", ref(r.Exists))
	addRef(out, "customize_diff", ref(r.CustomizeDiff))
	addRef(out, "migrate_state", ref(r.MigrateState))

	if boolField(r, "UseJSONNumber") {
		out["use_json_number"] = true
	}

	if r.Importer != nil {
		imp := map[string]any{"enabled": true}
		addRef(imp, "func", firstRef(r.Importer.StateContext, r.Importer.State))
		out["importer"] = imp
	}

	if len(r.StateUpgraders) > 0 {
		ups := make([]any, 0, len(r.StateUpgraders))
		for _, u := range r.StateUpgraders {
			up := map[string]any{"version": u.Version}
			addRef(up, "func", ref(u.Upgrade))
			ups = append(ups, up)
		}
		out["state_upgraders"] = ups
	}

	if ident := identityJSON(r); ident != nil {
		out["identity"] = ident
	}
	if boolField(r, "MutableIdentity") {
		out["mutable_identity"] = true
	}

	if t := r.Timeouts; t != nil {
		timeouts := map[string]any{}
		for name, d := range map[string]any{
			"create": t.Create, "read": t.Read, "update": t.Update, "delete": t.Delete, "default": t.Default,
		} {
			if rv := reflect.ValueOf(d); rv.IsValid() && !rv.IsNil() {
				timeouts[name] = rv.Elem().Interface().(interface{ String() string }).String()
			}
		}
		if len(timeouts) > 0 {
			out["timeouts"] = timeouts
		}
	}

	return out
}

// identityJSON dumps the resource identity schema (sdk v2.37+); read via reflection so
// the shim compiles against SDKs that predate it.
func identityJSON(r *schema.Resource) map[string]any {
	idv, ok := fieldValue(r, "Identity")
	if !ok || idv.Kind() != reflect.Ptr || idv.IsNil() {
		return nil
	}
	iv := idv.Elem()

	out := map[string]any{}
	if f := iv.FieldByName("Version"); f.IsValid() && f.CanInt() {
		out["version"] = f.Int()
	}
	if f := iv.FieldByName("SchemaFunc"); f.IsValid() && f.Kind() == reflect.Func && !f.IsNil() {
		if res := f.Call(nil); len(res) == 1 {
			if m, ok := res[0].Interface().(map[string]*schema.Schema); ok {
				sm := make(map[string]any, len(m))
				for k, s := range m {
					e := schemaJSON(s)
					addBool(e, "required_for_import", boolField(s, "RequiredForImport"))
					addBool(e, "optional_for_import", boolField(s, "OptionalForImport"))
					sm[k] = e
				}
				out["schema"] = sm
			}
		}
	}
	if f := iv.FieldByName("IdentityUpgraders"); f.IsValid() && f.Kind() == reflect.Slice && f.Len() > 0 {
		out["upgraders"] = f.Len()
	}

	return out
}

func schemaMapJSON(in map[string]*schema.Schema) map[string]any {
	out := make(map[string]any, len(in))
	for name, s := range in {
		out[name] = schemaJSON(s)
	}
	return out
}

func schemaJSON(s *schema.Schema) map[string]any {
	if s == nil {
		return nil
	}

	out := map[string]any{
		"type": s.Type.String(),
	}

	addBool(out, "required", s.Required)
	addBool(out, "optional", s.Optional)
	addBool(out, "computed", s.Computed)
	addBool(out, "force_new", s.ForceNew)
	addBool(out, "sensitive", s.Sensitive)
	addBool(out, "write_only", boolField(s, "WriteOnly"))
	addString(out, "description", s.Description)
	addString(out, "deprecated", s.Deprecated)
	addString(out, "input_default", s.InputDefault)

	switch s.ConfigMode {
	case schema.SchemaConfigModeAttr:
		out["config_mode"] = "attr"
	case schema.SchemaConfigModeBlock:
		out["config_mode"] = "block"
	}

	if s.Default != nil {
		out["default"] = jsonSafe(s.Default)
	}
	addRef(out, "default_func", ref(s.DefaultFunc))

	if s.MinItems != 0 {
		out["min_items"] = s.MinItems
	}
	if s.MaxItems != 0 {
		out["max_items"] = s.MaxItems
	}

	addStrings(out, "conflicts_with", s.ConflictsWith)
	addStrings(out, "exactly_one_of", s.ExactlyOneOf)
	addStrings(out, "at_least_one_of", s.AtLeastOneOf)
	addStrings(out, "required_with", s.RequiredWith)

	addRef(out, "validate_func", ref(s.ValidateFunc))
	addRef(out, "validate_diag_func", ref(anyField(s, "ValidateDiagFunc")))
	addRef(out, "diff_suppress_func", ref(s.DiffSuppressFunc))
	addBool(out, "diff_suppress_on_refresh", boolField(s, "DiffSuppressOnRefresh"))
	addRef(out, "state_func", ref(s.StateFunc))
	addRef(out, "set_func", ref(s.Set))

	switch e := s.Elem.(type) {
	case *schema.Schema:
		out["elem"] = map[string]any{"schema": schemaJSON(e)}
	case *schema.Resource:
		out["elem"] = map[string]any{"resource": resourceJSON(e, true)}
	case nil:
	default:
		out["elem"] = map[string]any{"unknown": fmt.Sprintf("%T", e)}
	}

	return out
}

var funcClosureRE = regexp.MustCompile("(\\.func[0-9]+)+(\\.[0-9]+)*$")

// ref resolves any func value into {name, origin, file, line} via runtime.FuncForPC.
// For closures returned by validator constructors (validation.IntBetween etc) the name
// ends in .funcN and points at the SDK; origin strips that suffix to give the
// constructor that built it.
func ref(v any) map[string]any {
	if v == nil {
		return nil
	}
	rv := reflect.ValueOf(v)
	if !rv.IsValid() || rv.Kind() != reflect.Func || rv.IsNil() {
		return nil
	}
	fn := runtime.FuncForPC(rv.Pointer())
	if fn == nil {
		return nil
	}

	name := fn.Name()
	file, line := fn.FileLine(fn.Entry())

	out := map[string]any{
		"name": name,
		"file": relFile(file),
		"line": line,
	}
	if origin := funcClosureRE.ReplaceAllString(name, ""); origin != name {
		out["origin"] = origin
	}
	return out
}

// firstRef returns the ref of the first non-nil func, mirroring the SDK's own
// precedence (WithoutTimeout > Context > legacy).
func firstRef(fns ...any) map[string]any {
	for _, fn := range fns {
		if r := ref(fn); r != nil {
			return r
		}
	}
	return nil
}

// relFile makes paths repo-relative; SDK/module-cache paths are shortened to their
// module-relative form prefixed with the module identity.
func relFile(file string) string {
	if cwd != "" {
		if rel, err := filepath.Rel(cwd, file); err == nil && !strings.HasPrefix(rel, "..") {
			return rel
		}
	}
	for _, marker := range []string{"/pkg/mod/", "/vendor/"} {
		if i := strings.Index(file, marker); i >= 0 {
			return file[i+len(marker):]
		}
	}
	return file
}

func jsonSafe(v any) any {
	if _, err := json.Marshal(v); err != nil {
		return fmt.Sprintf("%v", v)
	}
	return v
}

func addBool(m map[string]any, key string, v bool) {
	if v {
		m[key] = true
	}
}

func addString(m map[string]any, key, v string) {
	if v != "" {
		m[key] = v
	}
}

func addStrings(m map[string]any, key string, v []string) {
	if len(v) > 0 {
		m[key] = v
	}
}

func addRef(m map[string]any, key string, r map[string]any) {
	if r != nil {
		m[key] = r
	}
}

// fieldValue looks up a struct field by name via reflection, so the shim compiles
// against SDK versions that predate the field.
func fieldValue(v any, name string) (reflect.Value, bool) {
	rv := reflect.ValueOf(v)
	if rv.Kind() == reflect.Ptr {
		if rv.IsNil() {
			return reflect.Value{}, false
		}
		rv = rv.Elem()
	}
	if rv.Kind() != reflect.Struct {
		return reflect.Value{}, false
	}
	f := rv.FieldByName(name)
	return f, f.IsValid()
}

func boolField(v any, name string) bool {
	if f, ok := fieldValue(v, name); ok && f.Kind() == reflect.Bool {
		return f.Bool()
	}
	return false
}

func stringField(v any, name string) string {
	if f, ok := fieldValue(v, name); ok && f.Kind() == reflect.String {
		return f.String()
	}
	return ""
}

func anyField(v any, name string) any {
	if f, ok := fieldValue(v, name); ok && f.CanInterface() {
		return f.Interface()
	}
	return nil
}
`
